import AppKit

/// What Accessibility says about the focused element when the text is ready.
public struct FocusInfo: Equatable, Sendable {
    public var role: String?
    /// The element exposes a caret or selection (`AXSelectedTextRange`): it takes typed text.
    public var hasSelectedTextRange: Bool

    public init(role: String?, hasSelectedTextRange: Bool) {
        self.role = role
        self.hasSelectedTextRange = hasSelectedTextRange
    }

    /// The frontmost app didn't answer Accessibility in time (busy Electron, GC pause). Something has focus,
    /// we just can't see what: treat it as a field.
    public static let unanswered = FocusInfo(role: "AXUnanswered", hasSelectedTextRange: false)
}

/// How `insert.text` puts the text in.
public enum InsertPlan: Equatable, Sendable {
    /// ⌘V into the focused app, with the text briefly on the clipboard.
    case paste
    /// No place for the text (or no permission to type): leave it on the clipboard, and the app tells the person.
    case clipboardOnly(reason: String)

    /// Roles that are clearly not a place for text. Anything else gets the paste: Electron apps (Slack, Teams,
    /// VS Code) and terminals often expose their editor as a plain AXGroup or AXWebArea, and a paste that lands
    /// nowhere loses nothing (the text stays in the history), while refusing a real field would be wrong every time.
    public static let nonTextRoles: Set<String> = [
        "AXButton", "AXCheckBox", "AXRadioButton", "AXPopUpButton", "AXMenuButton", "AXMenuItem", "AXMenuBarItem",
        "AXImage", "AXSlider", "AXIncrementor", "AXDisclosureTriangle", "AXTabGroup", "AXToolbar", "AXDockItem",
    ]

    /// `focus` is nil when no app has a focused element (the desktop, or nothing frontmost).
    /// `secureInput`: some app holds Secure Event Input (a password field, Terminal's Secure Keyboard Entry),
    /// and macOS drops a synthetic ⌘V. Pasting would "succeed" and then the clipboard restore would erase the text.
    public static func decide(accessibilityGranted: Bool, secureInput: Bool = false, focus: FocusInfo?) -> InsertPlan {
        guard accessibilityGranted else { return .clipboardOnly(reason: "no_accessibility") }
        guard !secureInput else { return .clipboardOnly(reason: "secure_input") }
        guard let focus, let role = focus.role else { return .clipboardOnly(reason: "no_focus") }
        if focus.hasSelectedTextRange { return .paste }
        return nonTextRoles.contains(role) ? .clipboardOnly(reason: "no_text_field") : .paste
    }
}

/// A copy of everything on a pasteboard (every item, every type), to put back after the paste.
public struct ClipboardSnapshot {
    public let items: [[NSPasteboard.PasteboardType: Data]]

    /// Marks our own text so clipboard managers skip it (nspasteboard.org conventions).
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public static func take(_ pasteboard: NSPasteboard) -> ClipboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            Dictionary(item.types.compactMap { type in item.data(forType: type).map { (type, $0) } },
                       uniquingKeysWith: { first, _ in first })
        }
        return ClipboardSnapshot(items: items)
    }

    /// Puts `text` on the pasteboard for the paste and returns the change count that marks it as ours.
    @discardableResult
    public static func put(_ text: String, on pasteboard: NSPasteboard, transient: Bool) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            item.setData(Data(), forType: Self.transient)
            item.setData(Data(), forType: Self.autoGenerated)
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Puts the snapshot back, unless the person copied something else in the meantime
    /// (`changeCount` moved past ours): their new copy wins. Returns whether it restored.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard, ifStill ourChange: Int) -> Bool {
        guard pasteboard.changeCount == ourChange else { return false }
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let restored = items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
        return true
    }
}
