import AppKit

/// What Accessibility says about the focused element when the text is ready.
public struct FocusInfo: Equatable, Sendable {
    public var role: String?
    /// The element exposes a caret or selection (`AXSelectedTextRange`): it takes typed text.
    public var hasSelectedTextRange: Bool

    public init(role: String?, hasSelectedTextRange: Bool) {
        self.role = role
        self.hasSelectedTextRange = hasSelectedTextRange
    }

    /// The frontmost app didn't answer Accessibility in time (busy Electron, GC pause). Something has focus,
    /// we just can't see what: treat it as a field.
    public static let unanswered = FocusInfo(role: "AXUnanswered", hasSelectedTextRange: false)
}

/// How `insert.text` puts the text in.
public enum InsertPlan: Equatable, Sendable {
    /// ⌘V into the focused app, with the text briefly on the clipboard.
    case paste
    /// ⌘V, but the text stays on the clipboard afterwards (no restore). For when the paste may be dropped:
    /// if it is, the person can still paste by hand; if it lands, the cost is only the old clipboard not coming back.
    case pasteKeepingText(reason: String)
    /// No place for the text (or no permission to type): leave it on the clipboard, and the app tells the person.
    case clipboardOnly(reason: String)

    /// Roles that are clearly not a place for text. Anything else gets the paste: Electron apps (Slack, Teams,
    /// VS Code) and terminals often expose their editor as a plain AXGroup or AXWebArea, and a paste that lands
    /// nowhere loses nothing (the text stays in the history), while refusing a real field would be wrong every time.
    public static let nonTextRoles: Set<String> = [
        "AXButton", "AXCheckBox", "AXRadioButton", "AXPopUpButton", "AXMenuButton", "AXMenuItem", "AXMenuBarItem",
        "AXImage", "AXSlider", "AXIncrementor", "AXDisclosureTriangle", "AXTabGroup", "AXToolbar", "AXDockItem",
    ]

    /// `focus` is nil when Accessibility shows no focused element. `frontApp`: some app is in front (T984).
    /// `secureInput`: some app holds Secure Event Input (a password field, Terminal's Secure Keyboard Entry).
    /// macOS may drop a synthetic ⌘V then, and the flag is global (an app in the background can leak it on),
    /// so the paste still goes, but the text stays on the clipboard (#219).
    ///
    /// The paste goes whenever an app is in front (T984): the new Teams, a WebView, shows Accessibility no focused
    /// element (or one with no role) while its message box has the caret, and Wispr Flow and VoiceInk paste there all
    /// the same. Only with nothing in front, or without Accessibility, does the text stay on the clipboard alone.
    /// When the focus can't be seen (`no_focus`) or is clearly not a place for text (`no_text_field`, a button), the
    /// paste still goes but the text stays on the clipboard too: the same branch also catches the desktop with the
    /// Finder in front or an app with no window, where the ⌘V lands nowhere, and then nothing is lost (review #1007).
    public static func decide(
        accessibilityGranted: Bool, secureInput: Bool = false, focus: FocusInfo?, frontApp: Bool = false
    ) -> InsertPlan {
        guard accessibilityGranted else { return .clipboardOnly(reason: "no_accessibility") }
        guard let focus, let role = focus.role else {
            guard frontApp else { return .clipboardOnly(reason: "no_focus") }
            return .pasteKeepingText(reason: secureInput ? "secure_input" : "no_focus")
        }
        guard focus.hasSelectedTextRange || !nonTextRoles.contains(role) else {
            return .pasteKeepingText(reason: "no_text_field")
        }
        return secureInput ? .pasteKeepingText(reason: "secure_input") : .paste
    }
}

/// A copy of everything on a pasteboard (every item, every type), to put back after the paste.
public struct ClipboardSnapshot {
    public let items: [[NSPasteboard.PasteboardType: Data]]

    /// Marks our own text so clipboard managers skip it (nspasteboard.org conventions).
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// Who wrote it (nspasteboard.org), as VoiceInk's `ClipboardManager` does.
    public static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    public static let sourceID = "app.kiwinotes.desktop"

    public static func take(_ pasteboard: NSPasteboard) -> ClipboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            Dictionary(item.types.compactMap { type in item.data(forType: type).map { (type, $0) } },
                       uniquingKeysWith: { first, _ in first })
        }
        return ClipboardSnapshot(items: items)
    }

    /// Puts `text` on the pasteboard for the paste and returns the change count that marks it as ours.
    @discardableResult
    public static func put(_ text: String, on pasteboard: NSPasteboard, transient: Bool) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString(Self.sourceID, forType: Self.source)
        if transient {
            item.setData(Data(), forType: Self.transient)
            item.setData(Data(), forType: Self.autoGenerated)
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Puts the snapshot back, unless the person copied something else in the meantime
    /// (`changeCount` moved past ours): their new copy wins. Returns whether it restored.
    @discardableResult
    public func restore(to pasteboard: NSPasteboard, ifStill ourChange: Int) -> Bool {
        guard pasteboard.changeCount == ourChange else { return false }
        pasteboard.clearContents()
        guard !items.isEmpty else { return true }
        let restored = items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
        return true
    }
}

/// The clipboard side of `insert.text`, one dictation after another. A dictation that arrives while the previous
/// one's restore is still pending must not snapshot the previous dictation as "the person's clipboard": it keeps
/// the original snapshot, and only the latest restore puts it back.
/// (VoiceInk's `CursorPaster` gets the same by queuing each paste behind the previous restore; keeping the
/// snapshot does it without making the second dictation wait for the restore delay.)
public final class ClipboardKeeper {
    private var pending: (snapshot: ClipboardSnapshot, ours: Int)?

    public init() {}

    /// Puts `text` on the pasteboard and returns the change count that marks it as ours. With `keepOriginal`,
    /// what the person had there is remembered for `restore`; without it, the text stays and nothing comes back.
    @discardableResult
    public func put(_ text: String, on pasteboard: NSPasteboard, keepOriginal: Bool) -> Int {
        var original: ClipboardSnapshot?
        if keepOriginal {
            // Still our previous dictation on the clipboard: the person's content is the one we saved then.
            if let pending, pasteboard.changeCount == pending.ours {
                original = pending.snapshot
            } else {
                original = ClipboardSnapshot.take(pasteboard)
            }
        }
        let ours = ClipboardSnapshot.put(text, on: pasteboard, transient: keepOriginal)
        pending = original.map { ($0, ours) }
        return ours
    }

    /// Gives the person's clipboard back, if `ours` is still the latest dictation and nobody copied since.
    @discardableResult
    public func restore(on pasteboard: NSPasteboard, ifStill ours: Int) -> Bool {
        guard let pending, pending.ours == ours else { return false }
        self.pending = nil
        return pending.snapshot.restore(to: pasteboard, ifStill: ours)
    }
}

/// The space in front of a dictation that lands right after other text (T733): two dictations in a row in the same
/// field came out glued ("…sem acesso.Manda para…"). Wispr Flow and VoiceInk put one in too.
public enum LeadingSpace {
    /// Characters after which the text attaches with no space: an opening bracket or quote, a path or a handle.
    static let opening: Set<Character> = ["(", "[", "{", "«", "“", "‘", "¿", "¡", "/", "\\", "@", "#"]
    /// Characters a dictation can start with that attach to what came before ("…, e depois", "…)").
    static let attaching: Set<Character> = [".", ",", ";", ":", "!", "?", "…", ")", "]", "}", "»", "”", "’", "%"]

    /// Whether the text before the caret may be read at all. Only for a plain paste into a field that isn't a password
    /// field: with Secure Event Input on (`.pasteKeepingText`) or an `AXSecureTextField`, Accessibility would read a
    /// password, and a field that shows bullets would look like text and get a space pasted into the password (#787).
    public static func mayRead(plan: InsertPlan, role: String?) -> Bool {
        plan == .paste && role != "AXSecureTextField"
    }

    /// Whether to put a space in front of `text`.
    /// - Parameter before: up to the two characters before the caret; "" at the start of the field; nil when the field
    ///   can't be read (no Accessibility text: Electron, some web fields). Nil and "" give no space, as before T733.
    public static func needed(before: String?, text: String) -> Bool {
        guard let before, let previous = before.last, let first = text.first else { return false }
        if first.isWhitespace || attaching.contains(first) { return false }
        if previous.isWhitespace || opening.contains(previous) { return false }
        // A straight quote opens after a space or at the start ( ele disse "| ) and closes after text ( "Oi."| ).
        if previous == "\"" || previous == "'" {
            let earlier = before.dropLast().last
            return earlier.map { !$0.isWhitespace && !opening.contains($0) } ?? false
        }
        return true
    }

    /// Up to the two characters before `caret` (a UTF-16 offset, as Accessibility counts) in a field's whole value.
    /// For apps that answer `AXValue` but not `AXStringForRange`. Nil when the caret is past the end.
    public static func tail(of value: String, caret: Int) -> String? {
        let units = Array(value.utf16)
        guard caret >= 0, caret <= units.count else { return nil }
        return String(decoding: units[max(0, caret - 2)..<caret], as: UTF16.self)
    }
}
